/**
 * The golden-vector gate for the Node binding.
 *
 * This is the test the binding is worth anything without: a native binding that
 * can disagree with the Go library is worse than none, because it looks
 * authoritative while emitting different bytes. So every committed vector is
 * replayed through the Node API and compared to the JS reference
 * implementation's recorded output byte for byte -- preimage, payload and the
 * final signed entry, exactly as golden_test.go does on the Go side.
 *
 * The multisig vector is replayed too, through `authorizeWithSeeds`, so the
 * multi-key account path is proved rather than reimplemented here: if the test
 * had to build the signature vector itself, it would be testing this file.
 *
 * Keys are derived the way testdata/gen/gen.mjs derives them --
 * sha256(label) as an ed25519 raw seed -- so the vector's recorded signer labels
 * are all that is needed to sign as the vector did.
 *
 * Runs only when the binding is built; it skips loudly otherwise so
 * `node --test` stays useful on a machine without a Go toolchain.
 */

import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

// The binding is CommonJS (it is required from a Node backend, not imported
// into a page), so the test takes its default export and destructures. Named
// ESM imports off a CommonJS module only work for statically visible exports,
// and these are re-exported from lib/errors.js.
import soroauthBinding from "../index.js";

const {
  load,
  AlreadySigned,
  NoMatchingCredentialNode,
  SoroauthError,
  SourceAccountCredentials,
  TooManySignatures,
} = soroauthBinding;

const HERE = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = resolve(HERE, "..");
const PLATFORM = `${process.platform}-${process.arch}`;
const VECTORS_DIR = resolve(PACKAGE_ROOT, "..", "..", "testdata", "vectors");

const LIBRARY_NAME =
  process.platform === "darwin" ? "libsoroauth.dylib" : "libsoroauth.so";
const PREBUILD_DIR = join(PACKAGE_ROOT, "prebuilds", PLATFORM);
const built =
  existsSync(join(PREBUILD_DIR, "soroauth.node")) &&
  existsSync(join(PREBUILD_DIR, LIBRARY_NAME));

const skip = built
  ? false
  : `no binding for ${PLATFORM}; run \`npm run build\` in bindings/node first`;

/** referenceSDK is the only generator version a vector may come from. */
const referenceSDK = "@stellar/stellar-sdk@17.1.0";

/** seedHex is the raw seed the vector generator derives from a signer label. */
function seedHex(label) {
  return createHash("sha256").update(label).digest("hex");
}

function loadVectors() {
  const names = readdirSync(VECTORS_DIR)
    .filter((name) => name.endsWith(".json"))
    .sort();
  // A test that replays nothing would pass while proving nothing.
  assert.ok(names.length > 0, `no vectors found in ${VECTORS_DIR}`);
  return names.map((name) => ({
    name,
    vector: JSON.parse(readFileSync(join(VECTORS_DIR, name), "utf8")),
  }));
}

/** runSteps signs an unsigned entry through the API the vector calls for. */
function runSteps(soroauth, vector) {
  let entry = vector.unsigned_entry_xdr;
  for (const step of vector.steps) {
    const forAddress = step.for_address ?? "";
    entry = step.multisig
      ? soroauth.authorizeWithSeeds(
          entry,
          vector.valid_until_ledger,
          vector.network_passphrase,
          step.multisig.signer_labels.map(seedHex).join(","),
          forAddress,
        )
      : soroauth.authorizeWithSeed(
          entry,
          vector.valid_until_ledger,
          vector.network_passphrase,
          seedHex(step.signer_label),
          forAddress,
        );
  }
  return entry;
}

test("every golden vector replays through the Node binding byte for byte", { skip }, () => {
  const soroauth = load();
  const vectors = loadVectors();

  for (const { name, vector } of vectors) {
    assert.equal(
      vector.sdk,
      referenceSDK,
      `${name} was generated by ${vector.sdk}, want ${referenceSDK}`,
    );
    assert.equal(vector.schema_version, 1, `${name} has an unknown schema version`);

    const sourceAccount = isSourceAccountVector(soroauth, vector);

    if (sourceAccount) {
      // The source-account arm has no preimage to sign: the transaction
      // envelope covers it, and asking for one is an error rather than an
      // empty-but-successful result.
      assert.throws(
        () =>
          soroauth.preimage(
            vector.unsigned_entry_xdr,
            vector.valid_until_ledger,
            vector.network_passphrase,
          ),
        (error) => {
          assert.ok(error instanceof SourceAccountCredentials, `${name}: ${error}`);
          return true;
        },
        `${name}: preimage should refuse a source-account entry`,
      );
      assert.equal(
        soroauth.authorizeWithSeed(
          vector.unsigned_entry_xdr,
          vector.valid_until_ledger,
          vector.network_passphrase,
          seedHex("soroauth-vector-signer-1"),
          "",
        ),
        vector.signed_entry_xdr,
        `${name}: a source-account entry must pass through unchanged`,
      );
      continue;
    }

    const { preimageXdr, payloadHex } = soroauth.preimage(
      vector.unsigned_entry_xdr,
      vector.valid_until_ledger,
      vector.network_passphrase,
    );
    assert.equal(preimageXdr, vector.preimage_xdr, `${name}: preimage differs`);
    assert.equal(payloadHex, vector.payload_hex, `${name}: payload differs`);
    assert.equal(
      soroauth.payload(preimageXdr),
      vector.payload_hex,
      `${name}: payload(preimage) differs from the recorded payload`,
    );

    assert.equal(
      runSteps(soroauth, vector),
      vector.signed_entry_xdr,
      `${name}: the signed entry differs`,
    );
  }
});

/** isSourceAccountVector reports whether a vector's entry is the source arm. */
function isSourceAccountVector(soroauth, vector) {
  try {
    return (
      soroauth.inspect(vector.unsigned_entry_xdr).credential_type ===
      "source_account"
    );
  } catch {
    return false;
  }
}

test("the byte-equality check is discriminating", { skip }, () => {
  // A comparison against a recorded constant would pass while measuring
  // nothing. These two cases prove the comparison actually looks at the bytes:
  // the honest call matches the vector, and the same call with one ledger of
  // expiration or the wrong network does not.
  const soroauth = load();
  const vector = JSON.parse(
    readFileSync(join(VECTORS_DIR, "v2_single_testnet.json"), "utf8"),
  );
  const seed = seedHex("soroauth-vector-signer-1");

  assert.equal(runSteps(soroauth, vector), vector.signed_entry_xdr);
  assert.notEqual(
    soroauth.authorizeWithSeed(
      vector.unsigned_entry_xdr,
      vector.valid_until_ledger + 1,
      vector.network_passphrase,
      seed,
      "",
    ),
    vector.signed_entry_xdr,
    "one ledger of expiration must change the signed bytes",
  );
  assert.notEqual(
    soroauth.authorizeWithSeed(
      vector.unsigned_entry_xdr,
      vector.valid_until_ledger,
      "Public Global Stellar Network ; September 2015",
      seed,
      "",
    ),
    vector.signed_entry_xdr,
    "a different network must change the signed bytes",
  );
});

test("the binding reproduces the Go library's structure read-out", { skip }, () => {
  const soroauth = load();
  const vector = JSON.parse(
    readFileSync(join(VECTORS_DIR, "v2_single_testnet.json"), "utf8"),
  );
  const delegates = JSON.parse(
    readFileSync(join(VECTORS_DIR, "delegates_unsorted_with_nested.json"), "utf8"),
  );

  const info = soroauth.inspect(vector.unsigned_entry_xdr);
  assert.equal(info.credential_type, "address_v2");
  assert.equal(info.address_bound, true);
  // An entry straight from simulateTransaction carries no expiration and no
  // signature yet: the fields are omitted rather than guessed at.
  assert.equal(info.valid_until_ledger, undefined);
  assert.equal(info.top_level_signed, false);
  assert.equal(info.root_function, "transfer");

  // After signing, the entry reports the expiration that was written to it.
  const signedInfo = soroauth.inspect(runSteps(soroauth, vector));
  assert.equal(signedInfo.valid_until_ledger, vector.valid_until_ledger);
  assert.equal(signedInfo.top_level_signed, true);

  const delegateInfo = soroauth.inspect(delegates.unsigned_entry_xdr);
  assert.equal(delegateInfo.credential_type, "address_with_delegates");
  // The tree is reported in the entry's own (sorted) order, so the addresses
  // are the vector's, sorted: check membership rather than a fixed order.
  const recorded = delegates.delegates.map((d) => d.address);
  const reported = delegateInfo.delegates.map((d) => d.address);
  assert.deepEqual(
    [...reported].sort(),
    [...recorded].sort(),
    "the reported delegate addresses differ from the recorded ones",
  );

  const findings = soroauth.analyze(delegates.unsigned_entry_xdr);
  assert.ok(Array.isArray(findings), "analyze should return an array");
  for (const finding of findings) {
    assert.ok(finding.code && finding.severity && finding.rationale);
  }

  assert.match(
    soroauth.renderInvocations(vector.unsigned_entry_xdr),
    /transfer|create_contract/i,
  );
  assert.match(soroauth.renderTree(delegates.unsigned_entry_xdr), /G[A-Z0-9]{55}/);
});

test("Go sentinels survive the language boundary as distinct errors", { skip }, () => {
  const soroauth = load();
  const vector = JSON.parse(
    readFileSync(join(VECTORS_DIR, "v2_single_testnet.json"), "utf8"),
  );
  const delegates = JSON.parse(
    readFileSync(join(VECTORS_DIR, "delegates_single_node.json"), "utf8"),
  );

  // A decode failure is not a protocol refusal: it must not be reported as one.
  assert.throws(
    () => soroauth.inspect("not base64 xdr"),
    (error) => {
      assert.ok(error instanceof SoroauthError);
      assert.equal(error.kind, "ERROR");
      return true;
    },
  );

  // Signing for an address that owns no node is refused, not written anyway.
  assert.throws(
    () =>
      soroauth.authorizeWithSeed(
        vector.unsigned_entry_xdr,
        vector.valid_until_ledger,
        vector.network_passphrase,
        seedHex("soroauth-vector-delegate-1"),
        delegates.delegates[0].address,
      ),
    (error) => {
      assert.ok(error instanceof NoMatchingCredentialNode, String(error));
      return true;
    },
  );

  // More keys than the host's MAX_ACCOUNT_SIGNATURES = 20 is refused before
  // any signing happens, rather than failing on-chain after fees are paid.
  const tooMany = Array.from({ length: 21 }, (_, i) =>
    seedHex(`soroauth-binding-boundary-key-${i}`),
  ).join(",");
  assert.throws(
    () =>
      soroauth.authorizeWithSeeds(
        vector.unsigned_entry_xdr,
        vector.valid_until_ledger,
        vector.network_passphrase,
        tooMany,
        "",
      ),
    (error) => {
      assert.ok(error instanceof TooManySignatures, String(error));
      return true;
    },
  );

  // A delegate vector signed twice reports the second write as AlreadySigned
  // rather than silently re-signing with a payload the other nodes did not
  // commit to.
  const signed = runSteps(soroauth, delegates);
  assert.throws(
    () =>
      soroauth.authorizeWithSeed(
        signed,
        delegates.valid_until_ledger,
        delegates.network_passphrase,
        seedHex("soroauth-vector-delegate-1"),
        delegates.delegates[0].address,
      ),
    (error) => {
      assert.ok(error instanceof AlreadySigned, String(error));
      return true;
    },
  );
});
