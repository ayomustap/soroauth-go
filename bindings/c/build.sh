#!/usr/bin/env sh
# Build the soroauth C ABI shared library and its generated header.
#
# Usage: bindings/c/build.sh [outdir]
#
# Writes libsoroauth.so (Linux) or libsoroauth.dylib (macOS) plus the matching
# libsoroauth.h into [outdir] (default: a temp staging directory printed at the
# end). The library is build output, never committed; the Node binding builds it
# into its own prebuilds/ directory through scripts/build.mjs.
#
# The Go file carries an `ignore` build tag because cgo's c-shared mode needs a
# C toolchain for the target platform, which the repository's cross-compile
# matrix does not have. Naming the file explicitly (as below) compiles it anyway.
set -eu

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
root=$(CDPATH= cd -- "$here/../.." && pwd)
out=${1:-"$here/dist"}

case "$(uname -s)" in
  Linux) ext=so ;;
  Darwin) ext=dylib ;;
  *)
    echo "build.sh: unsupported OS for c-shared: $(uname -s)" >&2
    exit 1
    ;;
esac

mkdir -p "$out"
(
  cd "$root"
  go build -buildmode=c-shared -trimpath -o "$out/libsoroauth.$ext" bindings/c/soroauth.go
)

echo "wrote $out/libsoroauth.$ext"
echo "wrote $out/libsoroauth.h (generated by cgo)"
